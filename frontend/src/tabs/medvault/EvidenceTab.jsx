import { useEffect, useState } from "react";
import {
  Card, Badge, Stat, PrimaryButton, SecondaryButton, ErrorBanner, inputCls,
} from "../../components/Section";
import { api } from "../../api";
import { useOp, TraceCard, KeyValues, Verdict } from "../../components/medvault/shared";

function Table({ columns, rows, empty = "No rows." }) {
  if (!rows?.length) return <p className="text-2xs text-ink-500">{empty}</p>;
  return (
    <div className="overflow-auto max-h-80">
      <table className="w-full text-[13px]">
        <thead>
          <tr className="text-left text-2xs uppercase tracking-[0.08em] text-ink-500">
            {columns.map((c) => <th key={c.key} className="pb-2 pr-3 font-medium">{c.label}</th>)}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className="border-t border-ink-800/70">
              {columns.map((c) => (
                <td key={c.key} className={`py-1.5 pr-3 ${c.mono === false ? "" : "mono"} text-ink-300`}>
                  {String(row[c.key] ?? "—")}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

export default function EvidenceTab() {
  const [tables, setTables] = useState(null);
  const [meta, setMeta] = useState(null);
  const [chain, setChain] = useState(null);
  const [plotKey, setPlotKey] = useState(null);
  const [depth, setDepth] = useState(4);
  const [epoch, setEpoch] = useState(6);
  const [busy, setBusy] = useState(false);
  const [fullBusy, setFullBusy] = useState(false);
  const tree = useOp();

  const load = async (full = false) => {
    if (full) setFullBusy(true);
    try {
      const [t, m, c] = await Promise.all([
        api.mvTables(full), api.mvMeta(), api.mvChain(),
      ]);
      setTables(t.result);
      setMeta(m.result);
      setChain(c.result);
    } catch { /* first load may race the session */ }
    if (full) setFullBusy(false);
  };
  useEffect(() => { load(false); }, []);

  const advance = async () => {
    setBusy(true);
    const result = await tree.run(() => api.mvTree({
      depth: Number(depth), epoch: Number(epoch), measure_peks: true,
    }));
    setBusy(false);
    if (result) setPlotKey(Date.now());
  };

  const zk = tables?.zk;
  const pir = tables?.pir ?? [];
  // A tree built in this session measured its own PEKS matrix, so prefer it:
  // the quick tables run skips that measurement on purpose.
  const norms = tree.result?.peks?.epochs
    ? { ...tables?.tree_evolution_norm, ...tree.result,
        peks_same_epoch_matches: tree.result.peks.same_epoch_matches,
        peks_cross_epoch_matches: tree.result.peks.cross_epoch_matches,
        peks_epochs: tree.result.peks.epochs }
    : tables?.tree_evolution_norm;
  const storage = tables?.storage_overhead;
  const latency = tables?.search_latency_ms ?? [];
  const gas = chain?.gas && Object.keys(chain.gas).length ? chain.gas : null;
  const fullRun = (tables?.search_latency_ms ?? []).some((r) => r.mode === "A");

  return (
    <div className="space-y-4">
      <Card
        title="Evidence — every number is generated, none is typed in"
        subtitle="Regenerated by `repro.cmd` and by this endpoint. Sizes and outcomes reproduce; wall-clock timings are measurements of one machine."
        actions={<>
          <SecondaryButton onClick={() => load(false)}>Reload</SecondaryButton>
          <PrimaryButton onClick={() => load(true)} disabled={fullBusy}>
            {fullBusy ? "Measuring…" : "Full measurement"}
          </PrimaryButton>
        </>}
      >
        {meta && (
          <div className="flex flex-wrap gap-2">
            <Badge tone="blue">{meta.kem_label}</Badge>
            <Badge tone="neutral">{meta.ledger_backend}</Badge>
            <Badge tone={meta.zk_available ? "green" : "amber"}>{meta.proof_mode}</Badge>
            <Badge tone="neutral">seed {meta.seed}</Badge>
            <Badge tone="neutral">mode {meta.mode}</Badge>
          </div>
        )}
        <ErrorBanner message={tree.error} />
      </Card>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Card title="Attack outcomes" subtitle="Outcomes are deterministic for a given seed.">
          <Table
            columns={[
              { key: "attack", label: "Attack", mono: false },
              { key: "baseline", label: "Mode A" },
              { key: "hardened", label: "Mode B" },
            ]}
            rows={tables && [
              { attack: "KGA outsider", baseline: `${tables.kga_success.mode_A.outsider}%`, hardened: `${tables.kga_success.mode_B.outsider}%` },
              { attack: "KGA keyless server", baseline: `${tables.kga_success.mode_A.keyless_server}%`, hardened: `${tables.kga_success.mode_B.keyless_server}%` },
              { attack: "KGA insider", baseline: `${tables.kga_success.mode_A.insider}%`, hardened: `${tables.kga_success.mode_B.insider}%` },
              { attack: "Replay accepted", baseline: String(tables.replay_plant.mode_A.replay), hardened: String(tables.replay_plant.mode_B.replay) },
              { attack: "Plant matched", baseline: String(tables.replay_plant.mode_A.plant), hardened: String(tables.replay_plant.mode_B.plant) },
              { attack: "Token on chain", baseline: String(tables.access_pattern.mode_A.token_on_chain), hardened: String(tables.access_pattern.mode_B.token_on_chain) },
            ]}
          />
          <p className="text-2xs text-ink-500 mt-3 leading-relaxed">
            The insider row stays at 100% on purpose: a doctor who already holds the capability can
            match keywords inside their own scope. Claiming otherwise would be a false claim.
          </p>
        </Card>

        <Card title="Storage overhead" subtitle="Bytes, measured on one record of 256 bytes.">
          {storage ? (
            <KeyValues entries={{
              record_plaintext_bytes: storage.record_plaintext_bytes,
              record_ciphertext_bytes: storage.record_ciphertext_bytes,
              record_overhead_bytes: storage.record_overhead_bytes,
              envelope_bytes: storage.envelope_bytes,
              kem_ciphertext_bytes: storage.envelope_kem_ciphertext_bytes,
              sealed_payload_bytes: storage.envelope_sealed_payload_bytes,
              index_entry_bytes: storage.index_entry_bytes,
              index_token_bytes: storage.index_entry_token_bytes,
              index_signature_bytes: storage.index_entry_signature_bytes,
              kem_public_key_bytes: storage.kem?.public_key_bytes,
              kem_ciphertext_size: storage.kem?.ciphertext_bytes,
            }} />
          ) : <p className="text-2xs text-ink-500">Loading…</p>}
        </Card>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Card title="Search latency" subtitle="Keyed index vs a plaintext dict; the PPSEB column needs the full measurement.">
          <Table
            columns={[
              { key: "records", label: "Records" },
              { key: "doctors", label: "Doctors" },
              { key: "mode", label: "Mode" },
              { key: "plaintext", label: "Plaintext ms/q" },
              { key: "keyed", label: "Keyed ms/q" },
              { key: "ppseb", label: "PPSEB ms/q" },
            ]}
            rows={latency.map((r) => ({
              records: r.records, doctors: r.doctors, mode: r.mode,
              plaintext: r.plaintext_index_ms_per_query ?? "—",
              keyed: r.keyed_index_ms_per_query ?? "—",
              ppseb: r.ppseb_toy_ms_per_query ?? "—",
            }))}
          />
          {!fullRun && (
            <p className="text-2xs text-ink-500 mt-2">
              Quick grid: the PPSEB mode-A row is only measured by “Full measurement”.
            </p>
          )}
        </Card>

        <Card title="Private retrieval (LWE PIR)" subtitle="Sizes grow with the database; the query does not reveal the row.">
          <Table
            columns={[
              { key: "db_size", label: "Rows" },
              { key: "slot_size", label: "Slot B" },
              { key: "hint_bytes", label: "Hint B" },
              { key: "query_bytes", label: "Query B" },
              { key: "answer_bytes", label: "Answer B" },
              { key: "server_time_ms", label: "Server ms" },
            ]}
            rows={pir.map((r) => ({ ...r, slot_size: r.params?.slot_size }))}
          />
          <p className="text-2xs text-ink-500 mt-3 leading-relaxed">
            The search node still sees which record IDs matched; PIR hides the row the store is asked
            for. Collusion between the two defeats the privacy — stated, not hidden.
          </p>
        </Card>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
        <Card title="Zero-knowledge authorisation" subtitle="Groth16 over BN254, single-party dev ceremony.">
          {zk?.available ? (
            <>
              <div className="grid grid-cols-2 gap-3 mb-3">
                <Stat label="Constraints" value={zk.constraints} />
                <Stat label="Prove + search" value={`${zk.prove_and_search_ms} ms`} hint="includes one snarkjs run" />
                <Stat label="Verify" value={`${zk.verify_ms} ms`} />
                <Stat label="Proof" value={`${zk.proof_bytes} B`} hint="JSON, uncompressed" />
              </div>
              <Verdict ok={zk.verified}>proof verified off-chain against the current root</Verdict>
              <p className="text-2xs text-ink-500 mt-2">{zk.trusted_setup}</p>
            </>
          ) : <p className="text-2xs text-ink-500">{zk?.reason ?? "Loading…"}</p>}
        </Card>

        <Card title="Gas per consent event" subtitle={gas ? "Local Hardhat chain, chain id 31337." : "No gas in this session: the ledger backend is in-process."}>
          {gas ? (
            <Table
              columns={[
                { key: "operation", label: "Operation" },
                { key: "calls", label: "Calls" },
                { key: "mean", label: "Mean gas" },
                { key: "max", label: "Max gas" },
              ]}
              rows={Object.entries(gas).map(([operation, v]) => ({ operation, ...v }))}
            />
          ) : (
            <p className="text-2xs text-ink-500 leading-relaxed">
              Gas is measured on the Solidity backend. Start a local chain with{" "}
              <span className="mono">npm --prefix contracts run node</span>, compile with{" "}
              <span className="mono">npm --prefix contracts run compile</span>, then open a session
              with ledger = local Hardhat chain. The in-process ledger has no gas to report, and a
              number typed in here would be a fabricated one.
            </p>
          )}
        </Card>
      </div>

      <Card
        title="Lattice epoch key tree (research arm)"
        subtitle="Toy parameters. Correctness and measured norms, not a forward-security claim."
        actions={
          <>
            <label className="flex items-center gap-1.5 text-2xs text-ink-400">
              depth
              <input type="number" min={1} max={5} value={depth}
                onChange={(e) => setDepth(e.target.value)} className={`${inputCls} w-14`} />
            </label>
            <label className="flex items-center gap-1.5 text-2xs text-ink-400">
              target epoch
              <input type="number" min={0} value={epoch}
                onChange={(e) => setEpoch(e.target.value)} className={`${inputCls} w-16`} />
            </label>
            <PrimaryButton onClick={advance} disabled={busy}>
              {busy ? "Deriving…" : "Advance the frontier"}
            </PrimaryButton>
          </>
        }
      >
        {norms ? (
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
            <div>
              <div className="grid grid-cols-2 gap-3 mb-3">
                <Stat label="Nodes" value={Array.isArray(norms.nodes) ? norms.nodes.length : norms.nodes} />
                <Stat label="All correct" value={String(norms.all_nodes_correct)} tone={norms.all_nodes_correct ? "ok" : "break"} />
                <Stat label="PEKS same epoch"
                  value={norms.peks_epochs ? `${norms.peks_same_epoch_matches}/${norms.peks_epochs}` : "—"}
                  hint={norms.peks_epochs ? undefined : "measured when you advance the tree"} />
                <Stat label="PEKS cross epoch"
                  value={norms.peks_epochs ? norms.peks_cross_epoch_matches : "—"}
                  tone={norms.peks_cross_epoch_matches ? "break" : "ok"} />
              </div>
              <Table
                columns={[
                  { key: "level", label: "Level" },
                  { key: "count", label: "Nodes" },
                  { key: "max_norm", label: "Max ‖T̃‖" },
                  { key: "threshold", label: "Usable ≤" },
                ]}
                rows={norms.norms_per_level.map((r) => ({
                  level: r.level, count: r.count,
                  max_norm: r.max_norm.toFixed(2), threshold: r.threshold.toFixed(2),
                }))}
              />
              <p className="text-2xs text-ink-500 mt-2">{norms.claim}</p>
            </div>
            <div>
              <div className="text-2xs uppercase tracking-[0.08em] text-ink-500 mb-2">Measured norm per level</div>
              {plotKey ? (
                <img src={`${api.mvTreePlotUrl()}?t=${plotKey}`} alt="Measured Gram-Schmidt norm per tree level"
                  className="w-full rounded-lg ring-1 ring-inset ring-ink-800 bg-white/[0.02]" />
              ) : (
                <p className="text-2xs text-ink-500">Advance the frontier to draw the plot.</p>
              )}
            </div>
          </div>
        ) : (
          <p className="text-2xs text-ink-500">
            Not built in this session yet. Advancing derives every node with TrapGen/NewBasisDel and
            erases the epochs already passed.
          </p>
        )}
      </Card>

      {tree.result && (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
          <Card title="Current frontier" subtitle="Which subtree keys are retained after the advance.">
            <KeyValues entries={{
              epochs: tree.result.epochs,
              current_epoch: tree.result.current_epoch,
              frontier: tree.result.frontier,
              past_epoch_refused: tree.result.past_epoch_refused,
            }} />
          </Card>
          <TraceCard op={tree} title="Tree trace" subtitle="One event per derived node, with its norm." />
        </div>
      )}
    </div>
  );
}
